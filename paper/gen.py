    o.put("rqthree-projects", num(m["projects"]))
    o.put("rqthree-timeout-min", num(int(m["scan_timeout_seconds"]) // 60))
    o.put("rqthree-revision", tex(m["pqscope_revision"]))
    o.put("rqthree-criticality-commit", short_commit(m["criticality_source"]))

    dup = [r for r in selection if r["status"].startswith("duplicate")]
    o.put("rqthree-duplicates", num(len(dup)))
    last_sel = max(int(r["rank"]) for r in selection if not r["status"].startswith("duplicate"))
    o.put("rqthree-last-rank", num(last_sel))
    kernels = sum(1 for r in dup if "linux" in r["repo"].lower() or "kernel" in r["repo"].lower())
    o.put("rqthree-duplicates-kernel", num(kernels))

    skipped = [r for r in projects if r["status"].startswith("skipped")]
    o.put("rqthree-skipped", num(len(skipped)))
    caps = {re.search(r"above the (\d+) GB cap", r["status"]).group(1) for r in skipped}
    if len(caps) != 1:
        raise ValueError(f"expected one size cap, got {caps}")
    o.put("rqthree-cap-gb", caps.pop())
    def skipped_name(r):
        gb = re.search(r"is (\d+) GB", r["status"]).group(1)
        return f"\\texttt{{{tex(r['repo'])}}} ({gb}\\,GB)"

    o.put("rqthree-skipped-list", " and ".join(skipped_name(r) for r in skipped))
    failed = [r for r in projects if r["status"] == "clone failed"]
    o.put("rqthree-failed", num(len(failed)))
    o.put("rqthree-failed-list", " and ".join(f"\\texttt{{{tex(r['repo'])}}}" for r in failed))
    scanned = [r for r in projects if r["status"] == "scanned"]
    o.put("rqthree-scanned", num(len(scanned)))
    secs = [int(r["scan_seconds"]) for r in scanned]
    o.put("rqthree-scan-median", f"{statistics.median(secs):.0f}\\,s")
    if max(secs) >= int(m["scan_timeout_seconds"]):
        raise ValueError("a scan reached the time limit; revise sections/rq3.tex")

    def s(metric):
        return next(r for r in summary if r["metric"] == metric)

    keys = {
        "vulnerable:any-layer": "any",
        "vulnerable:used (source, config, binary)": "used",
        "vulnerable:layer:source": "source",
        "vulnerable:layer:config": "config",
        "vulnerable:layer:deps": "deps",
        "vulnerable:layer:binary": "binary",
        "vulnerable:exposure:network": "network",
        "vulnerable:exposure:internal": "internal",
        "vulnerable:exposure:test": "test",
        "derived:binary-without-source": "derived-bws",
        "derived:stale-dependency": "derived-stale",
    }
    for metric, k in keys.items():
        r = s(metric)
        o.put(f"rqthree-{k}-n", num(r["projects_with"]))
        o.put(f"rqthree-{k}-share", pct(r["share"]))
        o.put(f"rqthree-{k}-ci", pct_ci(r["ci95_low"], r["ci95_high"]))
        o.put(f"rqthree-{k}-findings", num(r["findings"]))
    if any(int(s(m_)["projects_scanned"]) != len(scanned) for m_ in keys):
        raise ValueError("rq3_summary and rq3_projects disagree on the scanned count")

    label = {
        "any": "Any layer",
        "used": "Used (source, config, binary)",
        "source": "\\quad source",
        "config": "\\quad config and keys",
        "deps": "\\quad dependencies",
        "binary": "\\quad binaries",
        "network": "\\quad network-facing",
        "internal": "\\quad internal",
        "test": "\\quad test and example",
        "derived-bws": "\\quad binary without source",
        "derived-stale": "\\quad stale dependency",
    }
    rows = []
    for metric, k in keys.items():
        if k == "source":
            rows.append(["\\emph{By layer}", "", "", "", ""])
        if k == "network":
            rows.append(["\\emph{By exposure class}", "", "", "", ""])
        if k == "derived-bws":
            rows.append(["\\emph{Derived findings}", "", "", "", ""])
        r = s(metric)
        rows.append(
            [label[k], num(r["projects_with"]), pct(r["share"]),
             pct_ci(r["ci95_low"], r["ci95_high"], 0).replace("\\%", ""), num(r["findings"])]
        )
    o.file(
        "tab_rq3_summary.tex",
        table("lrrrr", ["Projects with a finding", "$n$", "Share", "95\\% CI", "Findings"], rows),
    )

    # Concentration of findings.
    def vuln(r):
        return sum(int(r[c]) for c in ("vulnerable_source", "vulnerable_config", "vulnerable_deps", "vulnerable_binary"))

    total = sum(vuln(r) for r in scanned)
    if total != int(s("vulnerable:any-layer")["findings"]):
        raise ValueError("per-project counts don't sum to the summary's findings")
    ranked = sorted(scanned, key=lambda r: -vuln(r))
    top5 = ranked[:5]
    o.put("rqthree-top5-share", pct(sum(vuln(r) for r in top5) / total, 0))
    o.put("rqthree-top5-list", ", ".join(f"\\texttt{{{tex(r['repo'])}}}" for r in top5))
    top5_config = sum(int(r["vulnerable_config"]) for r in top5) / sum(vuln(r) for r in top5)
    o.put("rqthree-top5-config-share", pct(top5_config, 0))
    o.put("rqthree-top1-repo", f"\\texttt{{{tex(ranked[0]['repo'])}}}")
    o.put("rqthree-top1-findings", num(vuln(ranked[0])))
    with_any = [vuln(r) for r in scanned if vuln(r) > 0]
    o.put("rqthree-median-findings", f"{statistics.median(with_any):.0f}")

    # Projects whose primary language has a rule pack.
    covered = [r for r in scanned if r["language"] in SOURCE_LANGS]
    o.put("rqthree-covered", num(len(covered)))
    o.put("rqthree-uncovered", num(len(scanned) - len(covered)))
    langs = {}
    for r in scanned:
        if r["language"] not in SOURCE_LANGS:
            langs[r["language"]] = langs.get(r["language"], 0) + 1
    ordered = sorted(langs, key=lambda l: (-langs[l], l))
    o.put("rqthree-uncovered-top", " and ".join(tex(l) for l in ordered[:2]))
    o.put("rqthree-uncovered-others", num(len(ordered) - 2))
    cs = sum(1 for r in covered if int(r["vulnerable_source"]) > 0)
    o.put("rqthree-covered-source-n", num(cs))
    o.put("rqthree-covered-source-share", pct(cs / len(covered)))

    # Linux kernel: few library calls, as the limits section explains.
    kernel = next((r for r in scanned if r["repo"].endswith("/linux") or "linux-" in r["repo"]), None)
    if kernel:
        o.put("rqthree-kernel-repo", f"\\texttt{{{tex(kernel['repo'])}}}")
        o.put("rqthree-kernel-findings", num(vuln(kernel)))

    rows = [[tex(r["algorithm"]), num(r["projects"]), pct(int(r["projects"]) / len(scanned), 0), num(r["findings"])]
            for r in algorithms]
    o.file("tab_rq3_algorithms.tex", table("lrrr", ["Algorithm", "Projects", "Share", "Findings"], rows))
    for r in algorithms:
        o.put(f"rqthree-alg-{slug(r['algorithm'])}-projects", num(r["projects"]))
        o.put(f"rqthree-alg-{slug(r['algorithm'])}-share", pct(int(r["projects"]) / len(scanned), 0))


