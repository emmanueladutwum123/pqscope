TOOL_LABEL = {
    "pqscope": "pqscope",
    "cbomkit-action": "CBOMkit (action)",
    "cbomkit-theia": "CBOMkit-theia",
    "cryptoscan-pqc": "cryptoscan-pqc",
    "pqc-audit": "pqc-migration-audit",
    "semgrep": "Semgrep",
}

LANG_LABEL = {"go": "Go", "python": "Python", "java": "Java", "c": "C/C++", "js": "JS/TS"}


def rq1(o):
    summary = read("rq1_summary")
    tools = read("rq1_tools")
    corpus = read("rq1_corpus")
    ablation = read("rq1_ablation")

    o.put("rqone-cases", num(len(corpus)))
    o.put("rqone-labels", num(sum(int(r["labels"]) for r in corpus)))
    for kind in ("positive", "hard-positive", "hard-negative"):
        o.put(f"rqone-kind-{kind}", num(sum(1 for r in corpus if r["kind"] == kind)))
    for layer in ("source", "config", "deps", "binary", "network"):
        o.put(f"rqone-cases-{layer}", num(sum(1 for r in corpus if r["layer"] == layer)))
    for lang in LANG_LABEL:
        o.put(f"rqone-cases-{lang}", num(sum(1 for r in corpus if r["language"] == lang)))
    o.put("rqone-languages", num(len({r["language"] for r in corpus if r["layer"] == "source"})))

    ran = [t for t in tools if t["status"] == "ran"]
    competitors = [t["tool"] for t in ran if t["tool"] != "pqscope"]
    unavailable = [t for t in tools if t["status"] != "ran"]
    o.put("rqone-competitors", num(len(competitors)))
    o.put("rqone-unavailable", ", ".join(tex(t["tool"]) for t in unavailable) or "none")

    def row(tool, gran, layer="all", lang="all"):
        for r in summary:
            if (r["tool"], r["granularity"], r["layer"], r["language"]) == (tool, gran, layer, lang):
                return r
        raise KeyError((tool, gran, layer, lang))

    for t in ["pqscope"] + competitors:
        for g in ("file", "line"):
            r = row(t, g)
            for m, col in (("p", "precision"), ("r", "recall"), ("f", "f1")):
                o.put(f"rqone-{t}-{g}-{m}", dec(r[col]))
            o.put(f"rqone-{t}-{g}-tp", num(r["tp"]))
            o.put(f"rqone-{t}-{g}-fp", num(r["fp"]))
            o.put(f"rqone-{t}-{g}-fn", num(r["fn"]))

    best = max(competitors, key=lambda t: float(row(t, "file")["recall"]))
    o.put("rqone-best-competitor", TOOL_LABEL[best])
    o.put("rqone-best-competitor-r", dec(row(best, "file")["recall"]))
    o.put("rqone-best-competitor-p", dec(row(best, "file")["precision"]))
    o.put(
        "rqone-recall-ratio",
        ratio(row("pqscope", "file")["recall"], row(best, "file")["recall"]),
    )
    best_java = max(competitors, key=lambda t: float(row(t, "file", "source", "java")["recall"]))
    o.put("rqone-best-java-competitor", TOOL_LABEL[best_java])
    o.put("rqone-best-java-competitor-r", dec(row(best_java, "file", "source", "java")["recall"]))

    # Non-source layers: the most any competitor found there.
    for layer in ("config", "deps", "binary", "network"):
        o.put(
            f"rqone-competitors-{layer}-maxr",
            dec(max(float(row(t, "file", layer)["recall"]) for t in competitors)),
        )
        r = row("pqscope", "file", layer)
        o.put(f"rqone-pqscope-file-{layer}-r", dec(r["recall"]))
        o.put(f"rqone-pqscope-file-{layer}-p", dec(r["precision"]))
    nonsource_tp = sum(int(row("pqscope", "file", l)["tp"]) for l in ("config", "deps", "binary", "network"))
    nonsource_labels = sum(
        int(row("pqscope", "file", l)["tp"]) + int(row("pqscope", "file", l)["fn"])
        for l in ("config", "deps", "binary", "network")
    )
    total_labels = int(row("pqscope", "file")["tp"]) + int(row("pqscope", "file")["fn"])
    o.put("rqone-nonsource-labels", num(nonsource_labels))
    o.put("rqone-nonsource-share", pct(nonsource_labels / total_labels, 0))
    o.put("rqone-file-labels", num(total_labels))
    for lang in LANG_LABEL:
        r = row("pqscope", "file", "source", lang)
        o.put(f"rqone-pqscope-file-{lang}-r", dec(r["recall"]))
        o.put(f"rqone-pqscope-file-{lang}-p", dec(r["precision"]))
    by_lang = sorted(LANG_LABEL, key=lambda l: float(row("pqscope", "file", "source", l)["recall"]))
    o.put("rqone-pqscope-lang-min", LANG_LABEL[by_lang[0]])
    o.put("rqone-pqscope-lang-min-r", dec(row("pqscope", "file", "source", by_lang[0])["recall"]))
    o.put("rqone-pqscope-lang-max", LANG_LABEL[by_lang[-1]])
    o.put("rqone-pqscope-lang-max-r", dec(row("pqscope", "file", "source", by_lang[-1])["recall"]))

    # pqscope's misses, and the kind of case each is in.
    items = read("rq1_items")
    kind = {r["case"]: r["kind"] for r in corpus}
    misses = [r for r in items if r["tool"] == "pqscope" and r["granularity"] == "file" and r["outcome"] == "fn"]
    o.put("rqone-pqscope-misses", num(len(misses)))
    # The text says every miss is in a hard-positive case; stop if that changes.
    if any(kind[r["case"]] != "hard-positive" for r in misses):
        raise ValueError("a pqscope miss is outside the hard positives; revise sections/rq1.tex")
    o.put("rqone-pqscope-misses-source", num(sum(1 for r in misses if r["layer"] == "source")))
    if sum(1 for r in misses if r["layer"] != "source") != 1:
        raise ValueError("the text names exactly one non-source miss; revise sections/rq1.tex")

    # Table: overall P/R/F1 per tool, file and line granularity.
    order = sorted(["pqscope"] + competitors, key=lambda t: -float(row(t, "file")["f1"]))
    version = {t["tool"]: t["version"] for t in tools}
    rows = []
    for t in order:
        f, l = row(t, "file"), row(t, "line")
        name = f"\\textbf{{{TOOL_LABEL[t]}}}" if t == "pqscope" else TOOL_LABEL[t]
        v = "this work" if t == "pqscope" else tex(version[t])
        rows.append(
            [name, f"\\scriptsize {v}"]
            + [dec(f[c]) for c in ("precision", "recall", "f1")]
            + [dec(l[c]) for c in ("precision", "recall", "f1")]
        )
    o.file(
        "tab_rq1_tools.tex",
        table(
            "llrrrrrr",
            [
                "Tool",
                "Version",
                "\\multicolumn{3}{c}{File level}",
                "\\multicolumn{3}{c}{Line level}",
            ],
            [["", "", "P", "R", "F1", "P", "R", "F1"], "midrule"] + rows,
        ).replace(" \\\\\n\\midrule\n & ", " \\\\\n\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\n & ", 1),
    )

    # Table: file-level recall per layer and language, per tool.
    cols = order
    rows = []
    for lang in LANG_LABEL:
        rows.append(
            [f"source: {LANG_LABEL[lang]}", num(row("pqscope", "file", "source", lang)["cases"])]
            + [dec(row(t, "file", "source", lang)["recall"], 2) for t in cols]
        )
    for layer in ("config", "deps", "binary", "network"):
        rows.append(
            [layer, num(row("pqscope", "file", layer)["cases"])]
            + [dec(row(t, "file", layer)["recall"], 2) for t in cols]
        )
    rows.append("midrule")
    rows.append(["all", num(row("pqscope", "file")["cases"])] + [dec(row(t, "file")["recall"], 2) for t in cols])
    def head(t):
        return "\\textbf{" + TOOL_LABEL[t] + "}" if t == "pqscope" else TOOL_LABEL[t]

    hdr = ["Layer", "Cases"] + [head(t) for t in cols]
    o.file("tab_rq1_layers.tex", table("lr" + "r" * len(cols), hdr, rows))

    # Ablation.
    base = next(r for r in ablation if r["config"] == "all")
    rows = []
    for r in ablation:
        name = "all layers" if r["config"] == "all" else r["config"]
        drop = float(base["recall"]) - float(r["recall"])
        rows.append(
            [name, dec(r["precision"]), dec(r["recall"]), dec(r["f1"]), "--" if r is base else f"{100 * drop:.1f}"]
        )
        if r is not base:
            k = slug(r["config"])
            o.put(f"rqone-abl-{k}-r", dec(r["recall"]))
            o.put(f"rqone-abl-{k}-drop", f"{100 * drop:.1f}")
            o.put(f"rqone-abl-{k}-fn", num(r["fn"]))
    o.file(
        "tab_rq1_ablation.tex",
        table("lrrrr", ["Configuration", "P", "R", "F1", "$\\Delta$R (pp)"], rows),
    )


