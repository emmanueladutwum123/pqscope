SOURCE_LANGS = {"Go", "Python", "Java", "C", "C++", "JavaScript", "TypeScript"}


def rq3(o):
    m = meta("rq3_meta")
    summary = read("rq3_summary")
    projects = read("rq3_projects")
    selection = read("rq3_selection")
    algorithms = read("rq3_algorithms")

    o.put("rqthree-snapshot", m["criticality_snapshot"])
