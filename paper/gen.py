def read(name):
    with open(os.path.join(DATA, name + ".csv"), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def meta(name):
    return {r["key"]: r["value"] for r in read(name)}


def tex(s):
    """Escape text for LaTeX."""
    out = []
    for ch in str(s):
        if ch in "&%$#_{}":
            out.append("\\" + ch)
        elif ch == "~":
            out.append("\\textasciitilde{}")
        elif ch == "^":
            out.append("\\textasciicircum{}")
        elif ch == "\\":
            out.append("\\textbackslash{}")
        else:
            out.append(ch)
    return "".join(out)


def num(n):
    """An integer with thousands separators."""
    return f"{int(n):,}"


def pct(x, digits=1):
    return f"{100 * float(x):.{digits}f}\\%"


def pct_ci(lo, hi, digits=1):
    return f"{100 * float(lo):.{digits}f}--{100 * float(hi):.{digits}f}\\%"


def dec(x, digits=3):
    return f"{float(x):.{digits}f}"


def sig(x, n=3):
    """x to n significant figures, without an exponent."""
    x = float(x)
    if x == 0:
        return "0"
    digits = n - 1 - int(math.floor(math.log10(abs(x))))
    digits = max(digits, 0)
    return f"{round(x, digits):,.{digits}f}"


def dur(ns):
    """A duration in nanoseconds, in the largest unit that keeps it >= 1."""
    ns = float(ns)
    for unit, scale in (("s", 1e9), ("ms", 1e6), ("\\textmu s", 1e3)):
        if ns >= scale:
            return f"{sig(ns / scale)}\\,{unit}"
    return f"{sig(ns)}\\,ns"


def ms(ns, digits=2):
    return f"{float(ns) / 1e6:.{digits}f}\\,ms"


def ratio(a, b):
    return f"{float(a) / float(b):.1f}$\\times$"


def slug(s):
    s = re.sub(r"[^a-z0-9]+", "-", str(s).lower()).strip("-")
    return s


def short_commit(url_or_sha):
    m = re.search(r"\b([0-9a-f]{40})\b", url_or_sha)
    return m.group(1)[:7] if m else url_or_sha


class Out:
    def __init__(self):
        self.values = {}
        self.files = {}

    def put(self, key, value):
        if not re.fullmatch(r"[a-z0-9-]+", key):
            raise ValueError(f"bad key {key!r}")
        if key in self.values and self.values[key] != str(value):
            raise ValueError(f"key {key} set twice with different values")
        self.values[key] = str(value)

    def file(self, name, text):
        self.files[name] = text

    def numbers_tex(self):
        lines = [
            "% Generated by paper/gen.py from paper/data. Do not edit.",
            "% \\data{key} expands to the value; an unknown key stops the build.",
        ]
        for k in sorted(self.values):
            lines.append(f"\\expandafter\\def\\csname pqd@{k}\\endcsname{{{self.values[k]}}}")
        return "\n".join(lines) + "\n"


def table(colspec, header, rows, note=None):
    lines = [
        "% Generated by paper/gen.py from paper/data. Do not edit.",
        f"\\begin{{tabular}}{{{colspec}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
    ]
    for r in rows:
        if r == "midrule":
            lines.append("\\midrule")
        else:
            lines.append(" & ".join(r) + " \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    if note:
        lines.append(note)
    return "\n".join(lines) + "\n"


