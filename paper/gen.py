def generate(outdir):
    o = Out()
    rq1(o)
    rq2(o)
    rq3(o)
    riskabl(o)
    rq4(o)
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "numbers.tex"), "w", encoding="utf-8") as f:
        f.write(o.numbers_tex())
    for name, text in o.files.items():
        with open(os.path.join(outdir, name), "w", encoding="utf-8") as f:
            f.write(text)
    return ["numbers.tex"] + sorted(o.files)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if paper/generated/ is out of date")
    args = ap.parse_args()
    target = os.path.join(HERE, "generated")
    if not args.check:
        if os.path.isdir(target):
            shutil.rmtree(target)
        names = generate(target)
        print(f"wrote {len(names)} files to {os.path.relpath(target)}")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        names = generate(tmp)
        have = sorted(os.listdir(target)) if os.path.isdir(target) else []
        stale = [n for n in names if n not in have or not filecmp.cmp(os.path.join(tmp, n), os.path.join(target, n), shallow=False)]
        extra = [n for n in have if n not in names]
        if stale or extra:
            for n in stale:
                print(f"out of date: paper/generated/{n}", file=sys.stderr)
            for n in extra:
                print(f"not generated: paper/generated/{n}", file=sys.stderr)
            print("run: python3 paper/gen.py", file=sys.stderr)
            return 1
    print("paper/generated/ is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
