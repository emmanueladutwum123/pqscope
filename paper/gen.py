RQ2_AS = ["20940", "13335", "16509", "14618", "8075", "2635", "13506", "8987", "16524", "54113"]


def rq2(o):
    m = meta("rq2_meta")
    summary = read("rq2_summary")
    endpoints = read("rq2_endpoints")
    certs = read("rq2_certificates")

    o.put("rqtwo-domains", num(m["domains"]))
    o.put("rqtwo-endpoints", num(m["endpoints"]))
    o.put("rqtwo-date", m["scan_first_utc"][:10])
    o.put("rqtwo-scan-start", m["scan_first_utc"][11:16])
    o.put("rqtwo-scan-end", m["scan_last_utc"][11:16])
    minutes = (
        (int(m["run_end_utc"][11:13]) * 60 + int(m["run_end_utc"][14:16]))
        - (int(m["run_start_utc"][11:13]) * 60 + int(m["run_start_utc"][14:16]))
    )
    o.put("rqtwo-run-minutes", num(minutes))
    o.put("rqtwo-rate", num(m["rate_connections_per_second"]))
    o.put("rqtwo-dotgov-commit", short_commit(m["dotgov_source"]))
    o.put("rqtwo-asn-date", email.utils.parsedate_to_datetime(m["asn_last_modified"]).date().isoformat())
    o.put("rqtwo-exclude", num(m["exclude_entries"]))
    o.put("rqtwo-revision", tex(m["pqscope_revision"]))

    def srow(scope, by, key):
        return next(r for r in summary if (r["scope"], r["group_by"], r["key"]) == (scope, by, key))

    for scope, p in (("endpoint", "ep"), ("domain", "dom")):
        r = srow(scope, "all", "all")
        for col in ("n", "responding", "hybrid", "pq-only", "classical", "tls1.2-or-lower",
                    "tls-error", "unreachable", "unresolvable", "excluded"):
            o.put(f"rqtwo-{p}-{slug(col)}", num(r[col]))
        o.put(f"rqtwo-{p}-share", pct(r["hybrid_share"]))
        o.put(f"rqtwo-{p}-ci", pct_ci(r["ci95_low"], r["ci95_high"]))
        resp = int(r["responding"])
        o.put(f"rqtwo-{p}-classical-share", pct(int(r["classical"]) / resp))
        o.put(f"rqtwo-{p}-tlstwelve-share", pct(int(r["tls1.2-or-lower"]) / resp))
        tls13 = int(r["hybrid"]) + int(r["pq-only"]) + int(r["classical"])
        o.put(f"rqtwo-{p}-tlsthirteen", num(tls13))
        o.put(f"rqtwo-{p}-hybrid-of-tlsthirteen", pct(int(r["hybrid"]) / tls13))
        o.put(f"rqtwo-{p}-noresponse", num(int(r["n"]) - resp))

        for branch, b in (("Federal - Executive", "exec"), ("Federal - Legislative", "leg"),
                          ("Federal - Judicial", "jud")):
            br = srow(scope, "branch", branch)
            o.put(f"rqtwo-{p}-{b}-share", pct(br["hybrid_share"]))
            o.put(f"rqtwo-{p}-{b}-ci", pct_ci(br["ci95_low"], br["ci95_high"]))
            o.put(f"rqtwo-{p}-{b}-responding", num(br["responding"]))

    # Autonomous systems.
    asn = [r for r in summary if r["scope"] == "endpoint" and r["group_by"] == "asn"]
    asn.sort(key=lambda r: (-int(r["responding"]), r["key"]))
    total_resp = int(srow("endpoint", "all", "all")["responding"])
    o.put("rqtwo-ases", num(len(asn)))
    for r in asn:
        number = r["key"].split()[0][2:]
        if number in RQ2_AS:
            o.put(f"rqtwo-as{number}-share", pct(r["hybrid_share"]))
            o.put(f"rqtwo-as{number}-n", num(r["responding"]))
            o.put(f"rqtwo-as{number}-hybrid", num(r["hybrid"]))
            o.put(f"rqtwo-as{number}-tlstwelve", num(r["tls1.2-or-lower"]))
    topk = 12
    top = asn[:topk]
    o.put("rqtwo-asn-topk", num(topk))
    o.put("rqtwo-asn-topk-cover", pct(sum(int(r["responding"]) for r in top) / total_resp))
    top2 = asn[:2]
    o.put("rqtwo-top2-cover", pct(sum(int(r["responding"]) for r in top2) / total_resp))
    o.put(
        "rqtwo-top2-hybrid-cover",
        pct(sum(int(r["hybrid"]) for r in top2) / int(srow("endpoint", "all", "all")["hybrid"])),
    )

    def as_name(key):
        # "AS13335 CLOUDFLARENET - Cloudflare, Inc." -> "AS13335 Cloudflare, Inc."
        num_, _, rest = key.partition(" ")
        if num_[2:] in AS_LABEL:
            return f"{num_} {AS_LABEL[num_[2:]]}"
        rest = rest.split(" - ", 1)[1] if " - " in rest else rest
        rest = re.sub(r"^(AKAMAI-ASN1|GOVCLOUD) ", "", rest)
        return f"{num_} {rest}"

    rows = []
    for r in top:
        rows.append(
            [
                tex(as_name(r["key"])),
                num(r["responding"]),
                num(r["hybrid"]),
                num(r["classical"]),
                num(r["tls1.2-or-lower"]),
                pct(r["hybrid_share"]),
                pct_ci(r["ci95_low"], r["ci95_high"], 0).replace("\\%", ""),
            ]
        )
    rest = asn[topk:]
    rows.append("midrule")
    rows.append(
        [
            f"other {num(len(rest))} ASes",
            num(sum(int(r["responding"]) for r in rest)),
            num(sum(int(r["hybrid"]) for r in rest)),
            num(sum(int(r["classical"]) for r in rest)),
            num(sum(int(r["tls1.2-or-lower"]) for r in rest)),
            pct(sum(int(r["hybrid"]) for r in rest) / sum(int(r["responding"]) for r in rest)),
            "",
        ]
    )
    o.put("rqtwo-other-ases", num(len(rest)))
    o.put(
        "rqtwo-other-ases-share",
        pct(sum(int(r["hybrid"]) for r in rest) / sum(int(r["responding"]) for r in rest)),
    )
    o.file(
        "tab_rq2_asn.tex",
        table(
            "p{0.40\\linewidth}rrrrrr",
            ["Autonomous system", "TLS", "Hyb.", "Cl.", "$\\le$1.2", "Share", "95\\% CI"],
            rows,
        ),
    )

    # Figure: hybrid share with CI for the top ASes.
    coords, errs, labels = [], [], []
    for i, r in enumerate(reversed(top)):
        s = 100 * float(r["hybrid_share"])
        lo, hi = 100 * float(r["ci95_low"]), 100 * float(r["ci95_high"])
        coords.append(f"({s:.1f},{i}) += ({hi - s:.1f},0) -= ({s - lo:.1f},0)")
        number = r["key"].split()[0][2:]
        name = AS_LABEL.get(number) or as_name(r["key"]).split(" ", 1)[1]
        name = re.sub(r",? (Inc\.?|LLC|B\.V\.|Corporation|International)$", "", name)
        name = re.sub(r",? (Inc\.?|LLC|International)$", "", name)
        labels.append(tex(name))
    fig = [
        "% Generated by paper/gen.py from paper/data. Do not edit.",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  xbar, xmin=0, xmax=100, scale only axis, width=0.45\\linewidth, height=6cm,",
        "  xlabel={Endpoints negotiating a hybrid group (\\%)},",
        f"  ytick={{0,...,{len(top) - 1}}},",
        "  yticklabels={" + ",".join("{" + l + "}" for l in labels) + "},",
        "  y tick label style={font=\\scriptsize}, x tick label style={font=\\scriptsize},",
        "  label style={font=\\scriptsize}, bar width=5pt, enlarge y limits=0.05,",
        "]",
        "\\addplot+[error bars/.cd, x dir=both, x explicit] coordinates {",
    ]
    fig += ["  " + c for c in coords]
    fig += ["};", "\\end{axis}", "\\end{tikzpicture}"]
    o.file("fig_rq2_asn.tex", "\n".join(fig) + "\n")

    # Agencies with many TLS-speaking endpoints.
    ag = [r for r in summary if r["scope"] == "endpoint" and r["group_by"] == "agency"]
    min_resp = 20
    big = sorted((r for r in ag if int(r["responding"]) >= min_resp), key=lambda r: -float(r["hybrid_share"]))
    o.put("rqtwo-agencies", num(len(ag)))
    o.put("rqtwo-agency-min", num(min_resp))
    o.put("rqtwo-agencies-big", num(len(big)))
    rows = [
        [tex(r["key"]), num(r["responding"]), num(r["hybrid"]), pct(r["hybrid_share"]),
         pct_ci(r["ci95_low"], r["ci95_high"], 0).replace("\\%", "")]
        for r in big
    ]
    o.file(
        "tab_rq2_agencies.tex",
        table("p{0.46\\linewidth}rrrr", ["Agency", "TLS", "Hyb.", "Share", "95\\% CI"], rows),
    )
    # Does the provider or the agency decide? The same rule for both groupings:
    # the share of endpoints, in groups with >= uniform_min TLS endpoints, whose
    # group is nearly uniform (hybrid share <= lo or >= hi).
    uniform_min, lo, hi = 10, 0.10, 0.90
    o.put("rqtwo-uniform-min", num(uniform_min))
    o.put("rqtwo-uniform-lo", pct(lo, 0))
    o.put("rqtwo-uniform-hi", pct(hi, 0))
    for name, rows_ in (("as", asn), ("agency", ag)):
        sized = [r for r in rows_ if int(r["responding"]) >= uniform_min]
        covered = sum(int(r["responding"]) for r in sized)
        uniform = sum(int(r["responding"]) for r in sized
                      if float(r["hybrid_share"]) <= lo or float(r["hybrid_share"]) >= hi)
        o.put(f"rqtwo-uniform-{name}-groups", num(len(sized)))
        o.put(f"rqtwo-uniform-{name}-endpoints", num(covered))
        o.put(f"rqtwo-uniform-{name}-share", pct(uniform / covered))

    agshares = [float(r["hybrid_share"]) for r in big]
    o.put("rqtwo-agency-max", pct(max(agshares)))
    o.put("rqtwo-agency-min-share", pct(min(agshares)))
    o.put("rqtwo-agencies-big-zero", num(sum(1 for s in agshares if s == 0)))

    # Endpoint-level details.
    hrr = sum(1 for e in endpoints if e["hello_retry"] == "true")
    o.put("rqtwo-hello-retry", num(hrr))
    groups = {}
    for e in endpoints:
        if e["status"] in ("hybrid", "classical", "pq-only"):
            groups[e["group"]] = groups.get(e["group"], 0) + 1
    hybrid_groups = sorted(g for g in groups if "MLKEM" in g.upper() or "KYBER" in g.upper())
    o.put("rqtwo-hybrid-groups", ", ".join(tex(g) for g in hybrid_groups))
    if len(hybrid_groups) != 1:
        raise ValueError("more than one hybrid group; revise sections/rq2.tex")
    for g, k in (("x25519", "x25519"), ("secp256r1", "p256")):
        o.put(f"rqtwo-classical-{k}", num(groups.get(g, 0)))

    # Leaf certificates.
    total = sum(int(r["endpoints"]) for r in certs)
    rsa = sum(int(r["endpoints"]) for r in certs if r["leaf_public_key"].startswith("RSA"))
    ecdsa = sum(int(r["endpoints"]) for r in certs if r["leaf_public_key"].startswith("ECDSA"))
    other = total - rsa - ecdsa
    o.put("rqtwo-cert-endpoints", num(total))
    o.put("rqtwo-cert-rsa", num(rsa))
    o.put("rqtwo-cert-rsa-share", pct(rsa / total))
    o.put("rqtwo-cert-ecdsa", num(ecdsa))
    o.put("rqtwo-cert-ecdsa-share", pct(ecdsa / total))
    if other:
        raise ValueError("a leaf key is neither RSA nor ECDSA; revise sections/rq2.tex")
    rsa2048 = sum(int(r["endpoints"]) for r in certs if r["leaf_public_key"] == "RSA-2048")
    o.put("rqtwo-cert-rsa2048-share", pct(rsa2048 / total))

    # Cross-check: the probe's ServerHello group against the crypto/tls handshake's.
    # The probe records IANA names, crypto/tls its own; normalize to IANA. The two
    # clients offer different lists: crypto/tls also offers P-384 and P-521.
    go_names = {"X25519": "x25519", "CurveP256": "secp256r1", "CurveP384": "secp384r1",
                "CurveP521": "secp521r1"}
    both = same_class = same_group = 0
    unoffered = 0
    probe_offer = None
    with gzip.open(os.path.join(DATA, "raw", "rq2_net.jsonl.gz"), "rt", encoding="utf-8") as f:
        for line in f:
            rec = json.loads(line)
            hello = rec.get("hello") or {}
            a = hello.get("group")
            b = (rec.get("handshake") or {}).get("group")
            if not (a and b):
                continue
            probe_offer = probe_offer or hello.get("offered")
            b = go_names.get(b, b)
            both += 1
            same_class += ("MLKEM" in a.upper()) == ("MLKEM" in b.upper())
            if a == b:
                same_group += 1
            elif b not in hello.get("offered", []):
                unoffered += 1
    if both - same_group != unoffered:
        raise ValueError("a group differs between the probe and crypto/tls for a reason other than the offer lists")
    o.put("rqtwo-xcheck-both", num(both))
    o.put("rqtwo-xcheck-class", num(same_class))
    o.put("rqtwo-xcheck-group", num(same_group))
    o.put("rqtwo-xcheck-unoffered", num(unoffered))


